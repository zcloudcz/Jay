// ---------------------------------------------------------------------------
// ChannelPost.cs — A single public (plaintext) post in a channel
// ---------------------------------------------------------------------------
// Unlike QueuedMessage this is NOT store-and-forward: posts are kept for
// Channels:PostRetentionDays and offline followers pull them on reconnect.
// ChannelPostCleanupService is the only place that enforces retention.
// ---------------------------------------------------------------------------

namespace CallType.Api.Models;

/// <summary>
/// Kind of post. There is intentionally no Video in v1 (owner decision
/// 2026-09-17) — the only attachment is an image up to Channels:MaxImageBytes.
/// </summary>
public enum ChannelPostKind
{
    Text,
    Image,
    Poll
}

public class ChannelPost
{
    /// <summary>
    /// Generated by the CLIENT, not the server, so a retried POST with the same
    /// id is recognised as a duplicate (idempotent publish) instead of creating
    /// a second post.
    /// </summary>
    public Guid PostId { get; set; }

    public Guid ChannelId { get; set; }

    /// <summary>Admin device that published the post. Never returned to followers.</summary>
    public Guid AuthorDeviceId { get; set; }

    public ChannelPostKind Kind { get; set; }

    /// <summary>Plaintext (max 4096 chars) or, for polls, the poll definition as JSON.</summary>
    public string Body { get; set; } = string.Empty;

    /// <summary>
    /// Path of the unencrypted image inside the "channel-media" blob container,
    /// null for posts without an attachment. Removed together with the post.
    /// </summary>
    public string? AttachmentBlobPath { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>
    /// Soft delete by an admin — the row stays so clients that already cached
    /// the post can be sent a tombstone. Hard removal happens via retention.
    /// </summary>
    public DateTimeOffset? DeletedAt { get; set; }

    // Navigation properties
    public Channel Channel { get; set; } = null!;
}
