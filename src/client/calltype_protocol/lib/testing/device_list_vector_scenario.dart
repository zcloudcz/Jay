// Deterministic device-list test vectors (docs/protocol/devices.md).
//
// TEST SUPPORT, not protocol code (see session_vector_scenario.dart). Ed25519
// signatures are deterministic (RFC 8032), so fixed seeds give fixed bytes:
// tool/generate_vectors.dart writes test/vectors/device_list_v1.json and
// test/vectors/device_list_vectors_test.dart requires the code to reproduce
// it exactly and to accept it.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:cryptography/cryptography.dart';

import '../crypto/device_list.dart';

/// Relative to the calltype_protocol package root.
const deviceListVectorFile = 'test/vectors/device_list_v1.json';

List<int> _seed(String label) =>
    sha256.convert(utf8.encode('jay-vector-v1|$label')).bytes;

Future<Map<String, dynamic>> buildDeviceListVectors() async {
  const primaryId = '00000000-0000-4000-8000-0000000000a0';
  const companionIds = [
    '00000000-0000-4000-8000-0000000000a1',
    '00000000-0000-4000-8000-0000000000a2',
  ];
  final primarySeed = _seed('device-list|primary|signing');
  final primary = await Ed25519().newKeyPairFromSeed(primarySeed);
  final primaryPub = base64Encode((await primary.extractPublicKey()).bytes);

  final companions = <Map<String, dynamic>>[];
  final entries = <DeviceListEntry>[];
  for (final id in companionIds) {
    final signingSeed = _seed('device-list|$id|signing');
    final signing = await Ed25519().newKeyPairFromSeed(signingSeed);
    final identityPriv = _seed('device-list|$id|identity');
    final identity = await X25519().newKeyPairFromSeed(identityPriv);
    final consentSig = await signDeviceLinkConsent(
      companionSigningKey: signing,
      primaryDeviceId: primaryId,
      companionDeviceId: id,
    );
    final entry = DeviceListEntry(
      deviceId: id,
      identityKey: base64Encode((await identity.extractPublicKey()).bytes),
      signingKey: base64Encode((await signing.extractPublicKey()).bytes),
      consentSig: consentSig,
    );
    entries.add(entry);
    companions.add({
      'deviceId': id,
      'signingSeed': base64Encode(signingSeed),
      'identityPrivateKey': base64Encode(identityPriv),
      'entry': entry.toJson(),
    });
  }

  final signed = await signDeviceList(
    primarySigningKey: primary,
    list: DeviceList(primaryDeviceId: primaryId, version: 3, devices: entries),
  );
  // Fails loudly if the generated list does not verify.
  await verifyDeviceList(
    signed: signed,
    primarySigningKey: primaryPub,
    expectedPrimaryDeviceId: primaryId,
  );
  return {
    'description':
        'CallType signed device list v1 test vectors. Generated by '
        'tool/generate_vectors.dart (calltype_protocol). See '
        'docs/protocol/devices.md for the byte layout.',
    'version': 1,
    'primary': {
      'deviceId': primaryId,
      'signingSeed': base64Encode(primarySeed),
      'signingKey': primaryPub,
    },
    'companions': companions,
    'listVersion': 3,
    'payloadText': utf8.decode(base64Decode(signed.payload)),
    'signed': {'payload': signed.payload, 'signature': signed.signature},
  };
}

Map<String, dynamic> loadDeviceListVectors([
  String path = deviceListVectorFile,
]) => jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
